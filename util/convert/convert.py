"""Convert cookbook notebooks into developer-portal markdown tutorials.

A notebook is published only when a ``frontmatter.md`` sits next to it. The
generated file is named after the notebook's directory path (slashes become
hyphens) plus the notebook name, and is written to ``output_md/`` beside this
script. Paths are resolved from this file, so the script can be run from any
working directory.
"""

import os
from glob import glob

from nbconvert import MarkdownExporter
from nbformat import read

from logger import Logger
from preprocess import (
    StripANSICodesPreprocessor,
    HideWidgetOutputPreprocessor,
    HideLongPipInstallOutputPreprocessor,
)

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
PROJECT_DIR = os.path.abspath(os.path.join(SCRIPT_DIR, "..", ".."))
OUTPUT_DIR = os.path.join(SCRIPT_DIR, "output_md")
BASE_GITHUB_URL = "https://github.com/couchbase-examples/vector-search-cookbook/tree/main"

# Autogenerated markdown warning comment
AUTOGENERATED_MD_WARNING = "<!--- *** WARNING ***: Autogenerated markdown file from jupyter notebook. ***DO NOT EDIT THIS FILE***. Changes should be made to the original notebook file. See commit message for source repo. -->"


def build_exporter():
    """Return a MarkdownExporter with the cookbook's output-cleaning preprocessors."""
    exporter = MarkdownExporter()
    exporter.register_preprocessor(StripANSICodesPreprocessor, enabled=True)
    exporter.register_preprocessor(HideWidgetOutputPreprocessor, enabled=True)
    exporter.register_preprocessor(HideLongPipInstallOutputPreprocessor, enabled=True)
    return exporter


def find_notebooks(project_dir):
    """Return notebook paths under project_dir (hidden dirs such as .ipynb_checkpoints are skipped)."""
    return glob(os.path.join(project_dir, "**", "*.ipynb"), recursive=True)


def frontmatter_path_for(notebook_path):
    """Return the frontmatter.md path that gates publishing of notebook_path."""
    return os.path.join(os.path.dirname(notebook_path), "frontmatter.md")


def output_filename(relative_path):
    """Map a notebook path relative to the project root to its markdown file name."""
    notebook_name = os.path.splitext(os.path.basename(relative_path))[0]
    dir_name = os.path.dirname(relative_path).replace(os.sep, "-")
    return f"{dir_name}-{notebook_name}.md" if dir_name else f"{notebook_name}.md"


def render_markdown(frontmatter_content, body, relative_path):
    """Combine frontmatter, the autogenerated warning, a source link and the notebook body."""
    view_source_link = f"[View Source]({BASE_GITHUB_URL}/{relative_path})"
    return f"{frontmatter_content}\n\n{AUTOGENERATED_MD_WARNING}\n\n\n{view_source_link}\n\n{body}"


def convert_all(project_dir=PROJECT_DIR, output_dir=OUTPUT_DIR, exporter=None):
    """Convert every publishable notebook under project_dir; return the markdown paths written."""
    exporter = exporter or build_exporter()
    os.makedirs(output_dir, exist_ok=True)
    written = []

    for notebook_path in find_notebooks(project_dir):
        relative_path = os.path.relpath(notebook_path, project_dir)
        frontmatter_path = frontmatter_path_for(notebook_path)

        if not os.path.isfile(frontmatter_path):
            Logger.fail_conversion(relative_path, "frontmatter.md not found")
            continue

        with open(frontmatter_path, "r", encoding="utf-8") as frontmatter_file:
            frontmatter_content = frontmatter_file.read()

        with open(notebook_path, "r", encoding="utf-8") as f:
            notebook = read(f, as_version=4)

        body, _ = exporter.from_notebook_node(notebook)

        markdown_file = os.path.join(output_dir, output_filename(relative_path))
        with open(markdown_file, "w", encoding="utf-8") as f:
            f.write(render_markdown(frontmatter_content, body, relative_path))

        Logger.success_conversion(relative_path, markdown_file, "with frontmatter")
        written.append(markdown_file)

    return written


if __name__ == "__main__":
    convert_all()
