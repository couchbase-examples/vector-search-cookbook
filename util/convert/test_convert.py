"""Unit tests for the notebook -> markdown conversion. Run: python -m unittest -v"""

import os
import tempfile
import unittest

import nbformat
from nbformat.v4 import new_code_cell, new_markdown_cell, new_notebook, new_output

import convert


def write_notebook(path, cells):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        nbformat.write(new_notebook(cells=cells), f)


def write_text(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        f.write(text)


class OutputFilenameTest(unittest.TestCase):
    def test_nested_notebook_uses_hyphenated_directory_prefix(self):
        relative = os.path.join("azure", "query_based", "RAG.ipynb")
        self.assertEqual(convert.output_filename(relative), "azure-query_based-RAG.md")

    def test_top_level_notebook_has_no_prefix(self):
        self.assertEqual(convert.output_filename("intro.ipynb"), "intro.md")


class ProjectDirTest(unittest.TestCase):
    def test_project_dir_is_repo_root_regardless_of_cwd(self):
        self.assertTrue(
            os.path.isfile(os.path.join(convert.PROJECT_DIR, "util", "convert", "convert.py"))
        )


class ConvertAllTest(unittest.TestCase):
    def setUp(self):
        self._tmp = tempfile.TemporaryDirectory()
        self.project = os.path.join(self._tmp.name, "project")
        self.out = os.path.join(self._tmp.name, "out")
        self.addCleanup(self._tmp.cleanup)

    def test_only_notebooks_with_frontmatter_are_published(self):
        published = os.path.join(self.project, "cohere", "search_based", "nb.ipynb")
        write_notebook(published, [new_markdown_cell("# Hello")])
        write_text(os.path.join(os.path.dirname(published), "frontmatter.md"), "---\ntitle: T\n---")
        write_notebook(
            os.path.join(self.project, "draft", "nb.ipynb"), [new_markdown_cell("# Draft")]
        )

        written = convert.convert_all(self.project, self.out)

        self.assertEqual([os.path.basename(p) for p in written], ["cohere-search_based-nb.md"])
        self.assertEqual(os.listdir(self.out), ["cohere-search_based-nb.md"])
        with open(written[0], encoding="utf-8") as f:
            markdown = f.read()
        self.assertTrue(
            markdown.startswith("---\ntitle: T\n---\n\n" + convert.AUTOGENERATED_MD_WARNING)
        )
        self.assertIn(
            f"[View Source]({convert.BASE_GITHUB_URL}/cohere/search_based/nb.ipynb)", markdown
        )
        self.assertIn("# Hello", markdown)

    def test_hidden_checkpoint_notebooks_are_ignored(self):
        checkpoint = os.path.join(self.project, "x", ".ipynb_checkpoints", "nb-checkpoint.ipynb")
        write_notebook(checkpoint, [new_markdown_cell("# Old")])
        write_text(os.path.join(os.path.dirname(checkpoint), "frontmatter.md"), "---\n---")

        self.assertEqual(convert.convert_all(self.project, self.out), [])

    def test_exporter_strips_ansi_and_trims_pip_output(self):
        nb_path = os.path.join(self.project, "demo", "nb.ipynb")
        write_notebook(
            nb_path,
            [
                new_code_cell(
                    "%pip install foo",
                    outputs=[new_output("stream", name="stdout", text="x" * 501)],
                ),
                new_code_cell(
                    "print('hi')",
                    outputs=[new_output("stream", name="stdout", text="\x1b[31mred\x1b[0m")],
                ),
            ],
        )
        write_text(os.path.join(self.project, "demo", "frontmatter.md"), "---\n---")

        (written,) = convert.convert_all(self.project, self.out)
        with open(written, encoding="utf-8") as f:
            markdown = f.read()

        self.assertIn("[Output too long, omitted for brevity]", markdown)
        self.assertNotIn("x" * 501, markdown)
        self.assertIn("red", markdown)
        self.assertNotIn("\x1b[", markdown)


if __name__ == "__main__":
    unittest.main()
